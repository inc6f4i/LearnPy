# $5 \times 5$ 행렬이므로 총 25번 반복하는 '단 하나의' for문만 사용합니다.
for i in range(25):
    # i를 5로 나눈 몫은 '행(줄)', 나머지는 '열(칸)'이 됩니다.
    row = i // 5
    col = i % 5
    
    # 행과 열의 인덱스를 더한 값이 짝수면 'X', 홀수면 'O'를 출력하는 수학적 규칙성 활용
    if (row + col) % 2 == 0:
        print("X", end=" ")
    else:
        print("O", end=" ")
        
    # 한 줄(5칸)을 다 채우면(즉, col이 4일 때) 줄바꿈을 해줍니다.
    if col == 4:
        print()